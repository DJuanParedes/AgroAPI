CREATE TABLE IF NOT EXISTS rol (nombre VARCHAR(50) PRIMARY KEY);
CREATE TABLE IF NOT EXISTS privilegio (nombre VARCHAR(80) PRIMARY KEY);
CREATE TABLE IF NOT EXISTS rol_privilegio (
 rol VARCHAR(50) REFERENCES rol(nombre), privilegio VARCHAR(80) REFERENCES privilegio(nombre),
 PRIMARY KEY(rol, privilegio)
);
CREATE TABLE IF NOT EXISTS usuario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario VARCHAR(80) NOT NULL UNIQUE, nombre VARCHAR(160) NOT NULL,
 contrasena VARCHAR(100) NOT NULL, rol VARCHAR(50) NOT NULL REFERENCES rol(nombre)
);
CREATE TABLE IF NOT EXISTS lote (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(30) NOT NULL UNIQUE, nombre VARCHAR(160) NOT NULL,
 hectareas DOUBLE PRECISION NOT NULL, cultivo VARCHAR(100) NOT NULL,
 valle VARCHAR(100) NOT NULL, campania_cerrada BOOLEAN NOT NULL,
 dosis_maxima DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS labor (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lote_id BIGINT NOT NULL REFERENCES lote(id), tipo VARCHAR(30) NOT NULL,
 fecha DATE NOT NULL, responsable_id BIGINT NOT NULL REFERENCES usuario(id),
 cantidad DOUBLE PRECISION NOT NULL, observacion VARCHAR(1000) NOT NULL,
 creada_en TIMESTAMP WITH TIME ZONE NOT NULL
);
-- Actualiza también una base de la versión 1.0 sin perder registros.
ALTER TABLE labor ALTER COLUMN creada_en TIMESTAMP WITH TIME ZONE;
CREATE TABLE IF NOT EXISTS operacion (
 usuario_id BIGINT NOT NULL REFERENCES usuario(id), clave VARCHAR(100) NOT NULL,
 labor_id BIGINT NOT NULL, PRIMARY KEY(usuario_id, clave)
);
